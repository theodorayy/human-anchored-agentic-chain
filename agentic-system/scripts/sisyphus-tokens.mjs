// Generates the Sisyphus token stylesheet from new-ds/tokens.json and copies the
// component bundle into app/, so the design system can be regenerated in one step.
// Usage: pnpm tokens
import { copyFileSync, readFileSync, writeFileSync } from "node:fs"
import { resolve } from "node:path"

const root = resolve(import.meta.dirname, "..")
const tokens = JSON.parse(readFileSync(resolve(root, "new-ds/tokens.json"), "utf8"))

const light = []
const dark = []
for (const { name, value } of tokens.color.tokens) {
  light.push(`  --${name}: ${value.light};`)
  dark.push(`  --${name}: ${value.dark};`)
}
for (const group of ["spacing", "radius", "shadow"]) {
  for (const { name, value } of tokens[group].tokens) light.push(`  --${name}: ${value};`)
}
for (const [name, stack] of Object.entries(tokens.type.families)) light.push(`  --font-${name}: ${stack};`)

// One class per type style, e.g. .sy-t-display-xl, so screens can use the named styles.
const typeClasses = tokens.type.groups.flatMap(group =>
  group.styles.map(style => {
    const rules = [
      `font-family: var(--font-${group.family})`,
      `font-size: ${style.fontSize}`,
      `line-height: ${style.lineHeight}`,
      `font-weight: ${style.fontWeight}`,
      `font-style: ${style.fontStyle}`,
    ]
    if (style.letterSpacing) rules.push(`letter-spacing: ${style.letterSpacing}`)
    return `.sy-t-${style.name} { ${rules.join("; ")}; }`
  })
)

const css = `/* Generated by scripts/sisyphus-tokens.mjs from new-ds/tokens.json. Do not edit by hand. */
:root {
${light.join("\n")}
}

.dark,
[data-theme="dark"] {
${dark.join("\n")}
}

${typeClasses.join("\n")}
`

writeFileSync(resolve(root, "app/sisyphus-tokens.css"), css)
copyFileSync(resolve(root, "new-ds/components/bundle.css"), resolve(root, "app/sisyphus-components.css"))
console.log("Wrote app/sisyphus-tokens.css and app/sisyphus-components.css")
